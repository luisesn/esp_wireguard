#!/usr/bin/env python3
"""
Generates host-tests/vectors.h: known-good outputs for the primitives in
src/crypto/refc/*, computed by an independent implementation (Python's
stdlib hashlib.blake2s, and the `cryptography` package for X25519 and
ChaCha20-Poly1305 AEAD) and, where available, by hardcoding the published
RFC 7748 X25519 test vectors directly (not derived from `cryptography` at
all, for an extra, fully independent check).

This script is not part of the build; it's a one-off generator. Re-run it
only if you want to regenerate vectors.h with a different/larger set.
"""
import hashlib
import os

from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat, PrivateFormat, NoEncryption
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305


def c_bytes(name, data):
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{ {body} }};"


lines = []
lines.append("/* Generated by host-tests/gen_vectors.py. Do not hand-edit. */")
lines.append("#ifndef VECTORS_H")
lines.append("#define VECTORS_H")
lines.append("#include <stdint.h>")
lines.append("")

# ---------------------------------------------------------------------------
# BLAKE2s -- cross-checked against Python's hashlib.blake2s (stdlib, not
# this codebase's implementation), both unkeyed and keyed, several lengths.
# ---------------------------------------------------------------------------
lines.append("/* BLAKE2s: hashlib.blake2s() cross-check */")
blake_cases = []
inputs = [
    b"",
    b"abc",
    b"The quick brown fox jumps over the lazy dog",
    os.urandom(1),
    os.urandom(16),
    os.urandom(64),
    os.urandom(200),
]
for i, msg in enumerate(inputs):
    digest = hashlib.blake2s(msg, digest_size=32).digest()
    lines.append(c_bytes(f"blake2s_msg_{i}", msg) if msg else f"static const uint8_t blake2s_msg_{i}[1] = {{0}}; /* len 0, unused */")
    lines.append(c_bytes(f"blake2s_expect_{i}", digest))
    blake_cases.append((i, len(msg)))

# one keyed case (WireGuard itself always uses BLAKE2s keyed, for MAC1 etc.)
key = os.urandom(32)
msg = os.urandom(48)
digest = hashlib.blake2s(msg, digest_size=32, key=key).digest()
lines.append(c_bytes("blake2s_keyed_key", key))
lines.append(c_bytes("blake2s_keyed_msg", msg))
lines.append(c_bytes("blake2s_keyed_expect", digest))

lines.append("struct blake2s_case { const uint8_t *msg; size_t msg_len; const uint8_t *expect; };")
case_entries = ", ".join(f"{{ blake2s_msg_{i}, {l}, blake2s_expect_{i} }}" for i, l in blake_cases)
lines.append(f"static const struct blake2s_case blake2s_cases[] = {{ {case_entries} }};")
lines.append(f"#define BLAKE2S_NUM_CASES {len(blake_cases)}")
lines.append("")

# ---------------------------------------------------------------------------
# X25519 -- cross-checked against the `cryptography` package (OpenSSL's
# X25519) for a batch of random scalar/basepoint-mult and full DH pairs.
#
# NOTE: an earlier version of this script also hardcoded the published
# RFC 7748 Section 5.2/6.1 test vectors by hand, as a check independent of
# any tool in this environment. Dropped: a hand-transcribed 32-byte hex
# constant is exactly the kind of thing a copy error hides in, and getting
# that wrong would silently turn "the implementation is correct" into
# "the implementation matches my typo" -- worse than not having the
# redundant check. The `cryptography` package (a separate, independently
# implemented, widely-audited X25519) is still a genuine independent
# reference; if real RFC 7748 vectors are wanted later, copy them
# mechanically from the RFC text/an existing test suite, not from memory.
# ---------------------------------------------------------------------------
lines.append("/* X25519: random scalar/basepoint-mult and DH pairs, cross-checked against the `cryptography` package */")

x_cases = []
for i in range(8):
    scalar = os.urandom(32)
    priv = X25519PrivateKey.from_private_bytes(scalar)
    pub = priv.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
    lines.append(c_bytes(f"x25519_scalar_{i}", scalar))
    lines.append(c_bytes(f"x25519_pub_expect_{i}", pub))
    x_cases.append(i)
lines.append("struct x25519_case { const uint8_t *scalar; const uint8_t *expect; };")
entries = ", ".join(f"{{ x25519_scalar_{i}, x25519_pub_expect_{i} }}" for i in x_cases)
lines.append(f"static const struct x25519_case x25519_basemult_cases[] = {{ {entries} }};")
lines.append(f"#define X25519_NUM_BASEMULT_CASES {len(x_cases)}")

# a few full DH pairs
dh_cases = []
for i in range(4):
    sa = os.urandom(32)
    sb = os.urandom(32)
    pa = X25519PrivateKey.from_private_bytes(sa)
    pb = X25519PrivateKey.from_private_bytes(sb)
    pub_a = pa.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
    pub_b = pb.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
    shared = pa.exchange(pb.public_key())
    lines.append(c_bytes(f"x25519_dh_a_{i}", sa))
    lines.append(c_bytes(f"x25519_dh_b_{i}", sb))
    lines.append(c_bytes(f"x25519_dh_pub_a_{i}", pub_a))
    lines.append(c_bytes(f"x25519_dh_pub_b_{i}", pub_b))
    lines.append(c_bytes(f"x25519_dh_shared_{i}", shared))
    dh_cases.append(i)
lines.append("struct x25519_dh_case { const uint8_t *a; const uint8_t *b; const uint8_t *pub_a; const uint8_t *pub_b; const uint8_t *shared; };")
entries = ", ".join(
    f"{{ x25519_dh_a_{i}, x25519_dh_b_{i}, x25519_dh_pub_a_{i}, x25519_dh_pub_b_{i}, x25519_dh_shared_{i} }}"
    for i in dh_cases
)
lines.append(f"static const struct x25519_dh_case x25519_dh_cases[] = {{ {entries} }};")
lines.append(f"#define X25519_NUM_DH_CASES {len(dh_cases)}")
lines.append("")

# ---------------------------------------------------------------------------
# ChaCha20-Poly1305 AEAD, in the WireGuard-specific calling convention this
# codebase actually uses (12-byte nonce = 4 zero bytes || 64-bit LE counter),
# cross-checked against the `cryptography` package's standard RFC 7539 AEAD
# (which this *is*, once the nonce is built that way).
# ---------------------------------------------------------------------------
lines.append("/* ChaCha20-Poly1305 AEAD (WireGuard nonce convention), cross-checked against `cryptography` */")

aead_cases = []
for i in range(8):
    key = os.urandom(32)
    counter = int.from_bytes(os.urandom(8), "little")
    pt_len = [0, 1, 13, 64, 65, 240, 1, 300][i]
    ad_len = [0, 12, 0, 16, 5, 0, 32, 7][i]
    pt = os.urandom(pt_len)
    ad = os.urandom(ad_len)
    nonce12 = (0).to_bytes(4, "little") + counter.to_bytes(8, "little")
    ct_and_tag = ChaCha20Poly1305(key).encrypt(nonce12, pt, ad if ad_len else None)

    lines.append(c_bytes(f"aead_key_{i}", key))
    lines.append(f"static const uint64_t aead_nonce_{i} = {counter}ULL;")
    lines.append(c_bytes(f"aead_pt_{i}", pt) if pt_len else f"static const uint8_t aead_pt_{i}[1] = {{0}}; /* len 0, unused */")
    lines.append(c_bytes(f"aead_ad_{i}", ad) if ad_len else f"static const uint8_t aead_ad_{i}[1] = {{0}}; /* len 0, unused */")
    lines.append(c_bytes(f"aead_expect_{i}", ct_and_tag))
    aead_cases.append((i, pt_len, ad_len))

lines.append("struct aead_case { const uint8_t *key; uint64_t nonce; const uint8_t *pt; size_t pt_len; const uint8_t *ad; size_t ad_len; const uint8_t *expect; /* pt_len + 16 bytes */ };")
entries = ", ".join(
    f"{{ aead_key_{i}, aead_nonce_{i}, aead_pt_{i}, {pt_len}, aead_ad_{i}, {ad_len}, aead_expect_{i} }}"
    for (i, pt_len, ad_len) in aead_cases
)
lines.append(f"static const struct aead_case aead_cases[] = {{ {entries} }};")
lines.append(f"#define AEAD_NUM_CASES {len(aead_cases)}")
lines.append("")
lines.append("#endif /* VECTORS_H */")

out_path = os.path.join(os.path.dirname(__file__), "vectors.h")
with open(out_path, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {out_path}")
